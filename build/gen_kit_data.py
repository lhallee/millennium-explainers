"""Generate the figure kit's data with mpmath: the zero tables in shared/viz/zeros.js (200 ordinates to 10 decimals,
and 1,500 at full double precision behind Kit.zeroOrdinates), and the reference values that
build/test-kit.mjs compares the kit's math helpers against.

Run with the repository's virtual environment:

    .cache/venv/Scripts/python.exe build/gen_kit_data.py
"""

import base64
import json
import struct

from pathlib import Path

import mpmath

ROOT = Path(__file__).resolve().parent.parent
ZERO_COUNT = 200
LONG_COUNT = 1500
DIGITS = 30

# Points chosen to cover the kit's promise: |t| <= 200 and -10 <= sigma <= 10, away from the pole, including the
# critical line, both half-planes, negative t, a trivial zero, and points near s = 1 and s = 0.
ZETA_POINTS = [
    (2.0, 0.0),
    (0.5, 14.134725),
    (0.5, 100.0),
    (0.5, 199.5),
    (3.0, 50.0),
    (0.75, 150.0),
    (0.2, 7.0),
    (1.5, 0.1),
    (1.0, 1.0),
    (0.0, 0.0),
    (-2.0, 0.0),
    (-3.5, -80.0),
    (-5.0, 30.0),
    (-10.0, 0.5),
    (-10.0, 200.0),
    (10.0, 200.0),
    (5.0, -150.0),
    (-0.3, 120.0),
]
GAMMA_POINTS = [(0.5, 0.0), (5.0, 0.0), (0.25, 10.0), (-2.5, 1.0), (3.0, -40.0), (0.25, 100.0)]
Z_POINTS = [10.0, 14.134725141734694, 50.0, 100.0, 150.0, 199.0]
LI_POINTS = [1.5, 2.0, 10.0, 1000.0, 1.0e6]


def complex_pair(value: mpmath.mpc) -> list[float]:
    return [float(mpmath.re(value)), float(mpmath.im(value))]


def main() -> None:
    mpmath.mp.dps = DIGITS
    long_zeros = [float(mpmath.im(mpmath.zetazero(n))) for n in range(1, LONG_COUNT + 1)]
    zeros = long_zeros[:ZERO_COUNT]
    for got, want in zip(zeros[:3], (14.134725, 21.022040, 25.010858)):
        assert round(got, 6) == want, f"zero table check failed: {got} rounds to {round(got, 6)}, expected {want}"
    # The long table holds the doubles nearest the true ordinates: check a sample at higher precision.
    with mpmath.workdps(DIGITS + 20):
        for n in (1, 2, 200, 777, 1000, LONG_COUNT):
            exact = mpmath.im(mpmath.zetazero(n))
            assert long_zeros[n - 1] == float(exact), f"zero {n}: table {long_zeros[n - 1]!r}, mpmath {float(exact)!r}"
    assert all(a < b for a, b in zip(long_zeros, long_zeros[1:])), "the long zero table is not increasing"
    packed = base64.b64encode(struct.pack(f"<{LONG_COUNT}d", *long_zeros)).decode("ascii")

    lines = [f"  {z:.10f}," for z in zeros]
    zeros_js = (
        "/* Ordinates of the first 200 nontrivial zeros of zeta, gamma_1 < gamma_2 < ..., to 10 decimals.\n"
        "   Generated by build/gen_kit_data.py with mpmath.zetazero; do not edit by hand. */\n"
        "(function (global) {\n"
        "  'use strict';\n"
        "  var Kit = global.Kit = global.Kit || {};\n"
        "  Kit.zeros = [\n" + "\n".join(lines) + "\n  ];\n"
        f"  /* Kit.zeroOrdinates(n): the first n (default and at most {LONG_COUNT}) ordinates as a Float64Array, each the\n"
        "     double nearest the true value, decoded from little-endian doubles in base64 the first time it is called. */\n"
        f"  var LONG = '{packed}';\n"
        "  var table = null;\n"
        "  Kit.zeroOrdinates = function (n) {\n"
        f"    if (n == null) n = {LONG_COUNT};\n"
        f"    if (!(n >= 0 && n <= {LONG_COUNT})) throw new Error('Kit.zeroOrdinates holds {LONG_COUNT} ordinates, not ' + n);\n"
        "    if (!table) {\n"
        "      var bin = atob(LONG), bytes = new Uint8Array(bin.length);\n"
        "      for (var i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);\n"
        "      var view = new DataView(bytes.buffer);\n"
        f"      table = new Float64Array({LONG_COUNT});\n"
        f"      for (var k = 0; k < {LONG_COUNT}; k++) table[k] = view.getFloat64(8 * k, true);\n"
        "    }\n"
        "    return table.subarray(0, n);\n"
        "  };\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n"
    )
    (ROOT / "shared" / "viz" / "zeros.js").write_text(zeros_js, encoding="utf-8", newline="\n")

    reference = {
        "zeta": [{"s": [s, t], "value": complex_pair(mpmath.zeta(mpmath.mpc(s, t)))} for s, t in ZETA_POINTS],
        "gamma": [{"z": [x, y], "value": complex_pair(mpmath.gamma(mpmath.mpc(x, y)))} for x, y in GAMMA_POINTS],
        "Z": [{"t": t, "value": float(mpmath.siegelz(t))} for t in Z_POINTS],
        "li": [{"x": x, "value": float(mpmath.li(x))} for x in LI_POINTS],
        "zeros_first_three": zeros[:3],
    }
    (ROOT / "build" / "kit-reference.json").write_text(json.dumps(reference, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {ZERO_COUNT} zeros and a table of {LONG_COUNT}; first three {zeros[:3]}")


if __name__ == "__main__":
    main()
